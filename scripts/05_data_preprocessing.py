from pathlib import Path
import json
import pandas as pd

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

INPUT_PATH = Path("data/ai-detection-dataset.xlsx")
OUTPUT_PATH = Path("data/preprocessed_dataset.xlsx")
REPORT_PATH = Path("reports/preprocessing_report.json")

# Columns containing the three abstract versions
ABSTRACT_COLUMNS = [
    "Abstract",
    "Abstract-gpt3-5",
    "Abstract-Paraphrase",
]

# Important columns to inspect for missing values
IMPORTANT_COLUMNS = [
    "Title",
    "Year",
    "Abstract",
    "Abstract-gpt3-5",
    "Abstract-Paraphrase",
]


# --------------------------------------------------
# 2. Load dataset
# --------------------------------------------------

def load_dataset(path: Path) -> pd.DataFrame:
    """Load the dataset and validate the input file."""

    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {path}\n"
            "Please update INPUT_PATH to the correct file location."
        )

    data = pd.read_excel(path)

    print("=" * 60)
    print("DATASET OVERVIEW")
    print("=" * 60)
    print(f"Rows: {data.shape[0]}")
    print(f"Columns: {data.shape[1]}")
    print("\nColumn names:")
    print(data.columns.tolist())

    return data


# --------------------------------------------------
# 3. Preprocess and inspect dataset
# --------------------------------------------------

def preprocess_dataset(data: pd.DataFrame):
    """Perform preliminary preprocessing and generate a report."""

    report = {
        "initial_rows": int(len(data)),
        "initial_columns": int(len(data.columns)),
    }

    # Remove columns containing only missing values
    empty_columns = data.columns[data.isna().all()].tolist()
    data = data.dropna(axis=1, how="all").copy()

    report["removed_empty_columns"] = empty_columns

    # Report fully duplicated rows without deleting them
    duplicate_count = int(data.duplicated().sum())
    report["fully_duplicated_rows"] = duplicate_count

    # Identify columns that are available
    available_abstract_columns = [
        col for col in ABSTRACT_COLUMNS if col in data.columns
    ]

    report["missing_abstract_columns"] = [
        col for col in ABSTRACT_COLUMNS if col not in data.columns
    ]

    # Inspect empty or missing abstracts
    abstract_report = {}

    for col in available_abstract_columns:
        text = data[col].fillna("").astype(str).str.strip()
        empty_mask = text.eq("")

        abstract_report[col] = {
            "missing_values": int(data[col].isna().sum()),
            "empty_or_whitespace_only": int(empty_mask.sum()),
        }

    report["abstract_quality"] = abstract_report

    # Inspect missing values in important columns
    missing_report = {}

    for col in IMPORTANT_COLUMNS:
        if col in data.columns:
            missing_report[col] = int(data[col].isna().sum())

    report["missing_values_in_important_columns"] = missing_report

    # Normalize repeated whitespace in abstract text.
    # Missing values remain missing.
    whitespace_changes = {}

    for col in available_abstract_columns:
        original = data[col]
        valid_mask = original.notna()

        original_text = original.loc[valid_mask].astype(str)
        cleaned_text = original_text.str.replace(r"\s+", " ", regex=True).str.strip()

        whitespace_changes[col] = int(
            original_text.ne(cleaned_text).sum()
        )

        data.loc[valid_mask, col] = cleaned_text

    report["abstract_cells_with_whitespace_changes"] = whitespace_changes

    # Final dataset dimensions
    report["final_rows"] = int(len(data))
    report["final_columns"] = int(len(data.columns))
    report["remaining_missing_values"] = {
        col: int(count)
        for col, count in data.isna().sum().items()
        if count > 0
    }

    return data, report


# --------------------------------------------------
# 4. Save processed dataset and report
# --------------------------------------------------

def main():
    data = load_dataset(INPUT_PATH)

    processed_data, report = preprocess_dataset(data)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)

    processed_data.to_excel(OUTPUT_PATH, index=False)

    with REPORT_PATH.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=4, ensure_ascii=False)

    print("\n" + "=" * 60)
    print("PREPROCESSING REPORT")
    print("=" * 60)

    print(json.dumps(report, indent=4, ensure_ascii=False))

    print("\nPreprocessing completed.")
    print(f"Processed dataset: {OUTPUT_PATH}")
    print(f"Preprocessing report: {REPORT_PATH}")


if __name__ == "__main__":
    main()